def watch_codebase_overview(root: Path, interval: float = 2.0, max_iterations: int | None = None) -> dict[str, Any]:
    last_result = refresh_codebase_overview(root)
    last_fingerprint = _codebase_input_fingerprint(root)
    refresh_count = 1
    iterations = 0

    while max_iterations is None or iterations < max_iterations:
        time.sleep(interval)
        iterations += 1
        current = _codebase_input_fingerprint(root)
        if current == last_fingerprint:
            continue
        last_result = refresh_codebase_overview(root)
        last_fingerprint = current
        refresh_count += 1

    return {
        "generated_at": utc_now(),
        "refresh_count": refresh_count,
        "iterations": iterations,
        "last_fingerprint": last_fingerprint,
        "last_result": last_result,
    }


def load_codebase_map(root: Path) -> dict[str, Any]:
    payload = read_json(_map_path(root), default=None)
    if payload is None:
        refresh_codebase_overview(root)
        payload = read_json(_map_path(root), default={"generated_at": utc_now(), "entry_count": 0, "areas": {}, "entries": []})
    return payload


def _normalized_lookup_token(value: str) -> str:
    return value.strip().lower().replace("_", " ")


def _parse_lookup_query(query: str) -> tuple[dict[str, list[str]], list[str]]:
    supported_filters = {"layer", "owner", "surface", "module", "status", "path", "area", "kind"}
    filters: dict[str, list[str]] = defaultdict(list)
    free_tokens: list[str] = []
    for raw_token in query.split():
        token = raw_token.strip()
        if not token:
            continue
        if ":" in token:
            key, value = token.split(":", 1)
            key = key.strip().lower()
            value = _normalized_lookup_token(value)
            if key in supported_filters and value:
                filters[key].append(value)
                continue
        free_tokens.append(_normalized_lookup_token(token))
    return dict(filters), free_tokens


def _entry_matches_lookup_filters(entry: dict[str, Any], manifest: dict[str, Any], filters: dict[str, list[str]]) -> bool:
    surface_values = [_normalized_lookup_token(value) for value in manifest.get("surfaces_using", [])]
    candidates = {
        "layer": _normalized_lookup_token(manifest.get("layer", "")),
        "owner": _normalized_lookup_token(manifest.get("owner", "")),
        "status": _normalized_lookup_token(manifest.get("status", "")),
        "module": _normalized_lookup_token(manifest.get("module_id", "")),
        "path": _normalized_lookup_token(entry.get("path", "")),
        "area": _normalized_lookup_token(entry.get("area", "")),
        "kind": _normalized_lookup_token(entry.get("kind", "")),
    }
    for key, expected_values in filters.items():
        if key == "surface":
            if not all(any(expected in surface for surface in surface_values) for expected in expected_values):
                return False
            continue
        candidate = candidates.get(key, "")
        if not all(expected in candidate for expected in expected_values):
            return False
    return True


def lookup_codebase(root: Path, query: str, limit: int = 8) -> list[dict[str, Any]]:
    payload = load_codebase_map(root)
    manifests_by_path = {
        manifest["path"]: manifest
        for manifest in payload.get("module_index", {}).get("manifests", [])
        if isinstance(manifest, dict) and isinstance(manifest.get("path"), str)
    }
    filters, tokens = _parse_lookup_query(query)
    scored: list[dict[str, Any]] = []
    for entry in payload["entries"]:
        manifest = manifests_by_path.get(entry["path"], {})
        if filters and not _entry_matches_lookup_filters(entry, manifest, filters):
            continue
        haystack = " ".join(
            [
                entry["path"],
                entry["summary"],
                " ".join(entry.get("symbols", [])),
                " ".join(entry.get("imports_internal", [])),
                manifest.get("module_id", entry.get("module_manifest", {}).get("module_id", "")),
                manifest.get("layer", entry.get("module_manifest", {}).get("layer", "")),
                manifest.get("status", entry.get("module_manifest", {}).get("status", "")),
                manifest.get("owner", entry.get("module_manifest", {}).get("owner", "")),
                manifest.get("purpose", entry.get("module_manifest", {}).get("purpose", "")),
                " ".join(manifest.get("surfaces_using", [])),
            ]
        ).lower()
        score = len(filters) * 3 if filters else 0
        matched_tokens: list[str] = []
        for token in tokens:
            if token in haystack:
                score += 1
                matched_tokens.append(token)
            if token in entry["path"].lower():
                score += 2
            if token in entry["summary"].lower():
                score += 1
        if score <= 0:
            continue
        scored.append(
            {
                "path": entry["path"],
                "kind": entry["kind"],
                "area": entry["area"],
                "summary": entry["summary"],
                "symbols": entry.get("symbols", []),
                "module_manifest": entry.get("module_manifest"),
                "score": score,
                "matched_tokens": sorted(set(matched_tokens)),
            }
        )
    scored.sort(key=lambda row: (-row["score"], row["path"]))
    return scored[:limit]
