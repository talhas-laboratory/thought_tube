def _codebase_input_fingerprint(root: Path) -> str:
    digest = hashlib.sha256()
    for path in _tracked_input_paths(root):
        if not path.exists():
            continue
        digest.update(str(path.relative_to(root)).encode("utf-8"))
        stat = path.stat()
        digest.update(str(stat.st_mtime_ns).encode("utf-8"))
        digest.update(str(stat.st_size).encode("utf-8"))
    return digest.hexdigest()


def _safe_read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return path.read_text(encoding="utf-8", errors="ignore")


def _python_entry(root: Path, path: Path) -> dict[str, Any]:
    text = _safe_read_text(path)
    relative = str(path.relative_to(root))
    tree = ast.parse(text)
    symbols = [
        node.name
        for node in tree.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
    ]
    imports_internal: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module.startswith("conversation_os") or node.module.startswith("src.conversation_os"):
                imports_internal.append(node.module)
            elif node.level and node.module:
                imports_internal.append(node.module)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith("conversation_os") or alias.name.startswith("src.conversation_os"):
                    imports_internal.append(alias.name)
    docstring = ast.get_docstring(tree) or ""
    if not docstring:
        for line in text.splitlines():
            stripped = line.strip()
            if stripped.startswith("#") and not stripped.startswith("#!"):
                docstring = stripped.lstrip("#").strip()
                break
    area = relative.split("/", 2)[1] if relative.startswith("src/") and relative.count("/") >= 2 else relative.split("/", 1)[0]
    return {
        "path": relative,
        "kind": "python",
        "area": area,
        "summary": docstring or f"Python module at {relative}.",
        "symbols": symbols[:12],
        "imports_internal": sorted(set(imports_internal)),
    }


def _markdown_entry(root: Path, path: Path) -> dict[str, Any]:
    text = _safe_read_text(path)
    relative = str(path.relative_to(root))
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    summary = ""
    for line in lines:
        if line.startswith("#"):
            continue
        summary = line
        break
    area = relative.split("/", 1)[0]
    return {
        "path": relative,
        "kind": "document",
        "area": area,
        "summary": summary or f"Document at {relative}.",
        "symbols": [],
        "imports_internal": [],
    }


def _iter_tracked_paths(root: Path) -> list[Path]:
    paths: list[Path] = []
    for relative_root, suffixes in TRACKED_ROOTS:
        base = root / relative_root
        if not base.exists():
            continue
        for path in sorted(base.rglob("*")):
            if not path.is_file():
                continue
            if any(part in IGNORED_PARTS for part in path.parts):
                continue
            if path.suffix in suffixes:
                paths.append(path)
    for relative_path in TRACKED_SINGLE_FILES:
        path = root / relative_path
        if path.exists():
            paths.append(path)
    return paths


def _is_list_of_strings(value: Any) -> bool:
    return isinstance(value, list) and all(isinstance(item, str) for item in value)


def _validate_manifest(root: Path, path: Path, payload: dict[str, Any]) -> tuple[list[str], list[str]]:
    errors: list[str] = []
    warnings: list[str] = []
    relative = str(path.relative_to(root))
    for field, expected_type in MANIFEST_REQUIRED_FIELDS.items():
        if field not in payload:
            errors.append(f"{relative}: missing required field `{field}`")
            continue
        value = payload[field]
        if expected_type is list:
            if not _is_list_of_strings(value):
                errors.append(f"{relative}: field `{field}` must be a list of strings")
        elif not isinstance(value, expected_type):
            errors.append(f"{relative}: field `{field}` must be `{expected_type.__name__}`")

    for field, expected_type in MANIFEST_RECOMMENDED_FIELDS.items():
        if field not in payload:
            continue
        value = payload[field]
        if expected_type is list:
            if not _is_list_of_strings(value):
                errors.append(f"{relative}: field `{field}` must be a list of strings")
        elif not isinstance(value, expected_type):
            errors.append(f"{relative}: field `{field}` must be `{expected_type.__name__}`")

    layer = payload.get("layer")
    if isinstance(layer, str) and layer not in ALLOWED_LAYERS:
        errors.append(f"{relative}: layer `{layer}` is not allowed")
    status = payload.get("status")
    if isinstance(status, str) and status not in ALLOWED_STATUSES:
        errors.append(f"{relative}: status `{status}` is not allowed")

    module_path = payload.get("path")
    if isinstance(module_path, str):
        source_path = root / module_path
        if not source_path.exists():
            errors.append(f"{relative}: declared path `{module_path}` does not exist")

    compatibility_wrappers = payload.get("compatibility_wrappers", [])
    if status == "compatibility" and not compatibility_wrappers:
        warnings.append(f"{relative}: compatibility manifest does not declare any `compatibility_wrappers`")

    return errors, warnings


def load_module_manifests(root: Path) -> dict[str, Any]:
    manifests: list[dict[str, Any]] = []
    errors: list[str] = []
    warnings: list[str] = []
    by_path: dict[str, dict[str, Any]] = {}
    modules_dir = _modules_dir(root)
    for manifest_path in sorted(modules_dir.glob("*.json")):
        payload = read_json(manifest_path, default=None)
        if not isinstance(payload, dict):
            errors.append(f"{manifest_path.relative_to(root)}: manifest payload must be a JSON object")
            continue
        manifest_errors, manifest_warnings = _validate_manifest(root, manifest_path, payload)
        errors.extend(manifest_errors)
        warnings.extend(manifest_warnings)
        if manifest_errors:
            continue
        payload["manifest_path"] = str(manifest_path.relative_to(root))
        manifests.append(payload)
        declared_path = payload.get("path")
        if isinstance(declared_path, str):
            by_path[declared_path] = payload

    tracked_python_paths = [
        str(path.relative_to(root))
        for path in _iter_tracked_paths(root)
        if path.suffix == ".py" and str(path.relative_to(root)) not in MANIFEST_EXEMPT_PATHS
    ]
    missing_paths = sorted(path for path in tracked_python_paths if path not in by_path)
    if missing_paths:
        preview = ", ".join(missing_paths[:8])
        suffix = " ..." if len(missing_paths) > 8 else ""
        warnings.append(f"{len(missing_paths)} tracked python modules do not yet have manifests: {preview}{suffix}")

    known_ids = {
        manifest["module_id"]
        for manifest in manifests
        if isinstance(manifest.get("module_id"), str)
    }
    for manifest in manifests:
        for dependency in manifest.get("depends_on", []):
            if dependency.startswith("external:") or dependency in known_ids:
                continue
            warnings.append(
                f"{manifest['manifest_path']}: dependency `{dependency}` does not resolve to a manifest in the current tranche"
            )
        for consumer in manifest.get("feeds_into", []):
            if consumer.startswith("external:") or consumer in known_ids:
                continue
            warnings.append(
                f"{manifest['manifest_path']}: downstream reference `{consumer}` does not resolve to a manifest in the current tranche"
            )

    return {
        "generated_at": utc_now(),
        "manifest_count": len(manifests),
        "manifests": manifests,
        "by_path": by_path,
        "errors": errors,
        "warnings": warnings,
        "missing_paths": missing_paths,
    }


def inspect_codebase_index(root: Path) -> dict[str, Any]:
    tracked_inputs = _tracked_input_paths(root)
    generated_paths = _generated_artifact_paths(root)

    newest_source_path = ""
    newest_source_mtime = 0.0
    for path in tracked_inputs:
        try:
            mtime = path.stat().st_mtime
        except FileNotFoundError:
            continue
        if mtime >= newest_source_mtime:
            newest_source_mtime = mtime
            newest_source_path = str(path.relative_to(root))

    missing_artifacts = [str(path.relative_to(root)) for path in generated_paths if not path.exists()]

    newest_generated_path = ""
    newest_generated_mtime = 0.0
    stale_reasons: list[str] = []
    if missing_artifacts:
        stale_reasons.append(
            "Generated codebase artifacts are missing: " + ", ".join(missing_artifacts)
        )
    else:
        newest_generated = max(generated_paths, key=lambda path: path.stat().st_mtime)
        newest_generated_mtime = newest_generated.stat().st_mtime
        newest_generated_path = str(newest_generated.relative_to(root))
        if newest_source_mtime > newest_generated_mtime:
            stale_reasons.append(
                "Generated codebase artifacts are older than the newest tracked source or manifest "
                f"({newest_generated_path} < {newest_source_path})."
            )

    return {
        "generated_at": utc_now(),
        "tracked_input_count": len(tracked_inputs),
        "generated_artifact_count": len(generated_paths),
        "fresh": not stale_reasons,
        "stale_reasons": stale_reasons,
        "missing_artifacts": missing_artifacts,
        "newest_source_path": newest_source_path,
        "newest_source_mtime": newest_source_mtime,
        "newest_generated_path": newest_generated_path,
        "newest_generated_mtime": newest_generated_mtime,
    }


